// Writes src/data/citationLabels.js: for every bibliography, the author-year label of each entry.
// The Citation component uses it for form="parenthetical" / "narrative", so the text is in the
// static HTML (search indexing) and always matches bib.json.
const fs = require('fs');
const path = require('path');
const { globSync } = require('glob');
const { citationLabel } = require('./lib/citationLabel');

const root = path.join(__dirname, '..');
const bibRoot = path.join(root, 'static', 'bibliographies');
const outDir = path.join(root, 'src', 'data');
const outFile = path.join(outDir, 'citationLabels.js');

const labels = {};
let count = 0;
for (const file of globSync('**/bib.json', { cwd: bibRoot })) {
  const docKey = path.dirname(file).split(path.sep).join('/'); // e.g. web-applications/system-response/x/v1.0
  let entries;
  try {
    entries = JSON.parse(fs.readFileSync(path.join(bibRoot, file), 'utf8'));
  } catch (e) {
    console.warn(`⚠️ citation labels: could not read ${file}: ${e.message}`);
    continue;
  }
  if (!Array.isArray(entries)) continue;
  labels[docKey] = {};
  for (const entry of entries) {
    if (!entry?.citationKey) continue;
    labels[docKey][entry.citationKey] = citationLabel(entry);
    count++;
  }
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, `// Auto-generated by scripts/generateCitationLabels.js — DO NOT EDIT\nmodule.exports = ${JSON.stringify(labels)};\n`);
console.log(`✅ Citation labels: ${count} entries → ${path.relative(root, outFile)}`);
